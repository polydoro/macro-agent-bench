"""Write the full rubric text (as sent to the judge, in Portuguese) to docs/rubric-simple-tasks.md and
docs/rubric-complex-tasks.md. No API calls; reads only the rubric modules.

    python scoring/dump_rubrics.py
"""
import importlib.util
import os

HERE = os.path.dirname(os.path.abspath(__file__))
DOCS = os.path.join(HERE, '..', 'docs')


def load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def options_md(options):
    out = []
    for kind, opts in options.items():
        out.append(f'**{kind}**\n')
        out += [f'- `{k}`: {v}' for k, v in opts.items()]
        out.append('')
    return out


def task_md(rubric, task):
    out = [f'## {task}', '']
    groups = rubric.groups(task)
    if groups:
        out.append('Best-K groups (only the K best members count): ' + ', '.join(f'`{g}` K={k}' for g, k in groups.items()))
        out.append('')
    out += ['| Id | Kind | Points | Group | Question |', '|---|---|---:|---|---|']
    for qid, q in rubric.questions(task).items():
        text = q['text'].replace('|', '\\|').replace('\n', ' ')
        out.append(f"| `{qid}` | {q['kind']} | {q['weight']:.2f} | {q.get('group') or ''} | {text} |")
    spec = rubric.TASKS[task]
    for key in ('request', 'context', 'identity', 'conventions', 'method'):
        if isinstance(spec.get(key), str):
            out += ['', f'*{key}*: ' + spec[key].replace('\n', ' ')]
    out.append('')
    return out


def write(rubric, title, intro, path, extra=()):
    lines = [f'# {title}', '', intro, '', f'Rubric version: `{rubric.VERSION}`.', '', '## Instructions common to every request', '']
    lines += ['```', rubric.COMMON, '```', '', '## Answer options', '']
    lines += options_md(rubric.OPTIONS)
    for task in rubric.TASKS:
        lines += task_md(rubric, task)
    lines += list(extra)
    open(path, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    print(path)


if __name__ == '__main__':
    s = load('srubric', os.path.join(HERE, 'visual-rubric-v1', 'rubric.py'))
    write(s, 'Rubric: simple tasks (S01–S11), full text',
          'Generated by `scoring/dump_rubrics.py` from `scoring/visual-rubric-v1/rubric.py`. Question text is in Portuguese, as sent. '
          'Numeric questions (`N_*`) are sent in a separate request as blind value-range questions; their options are built per '
          'delivery from the answer key (`references.py`) and the reference value is never shown. Of their points, 75% go to '
          'correctness checked in code and 25% to legibility; see docs/scoring.md.',
          os.path.join(DOCS, 'rubric-simple-tasks.md'))
    c = load('crubric', os.path.join(HERE, 'c-rubric-v1', 'rubric.py'))
    write(c, 'Rubric: complex tasks (C01–C05), full text',
          'Generated by `scoring/dump_rubrics.py` from `scoring/c-rubric-v1/rubric.py`. Question text is in Portuguese, as sent. '
          'Weights below are the rubric points (out of 100) before the 100-point result/method split described in docs/scoring.md. '
          'The verdict questions and gold categories are in `scoring/c-rubric-v1/gold/verdict.py`.',
          os.path.join(DOCS, 'rubric-complex-tasks.md'))
